export function getTestCaseById(id) {
  return TEST_CASES.find(testCase => testCase.id === id)
}

export function buildTestCaseSelectOptions(t) {
  return TEST_CASE_GROUPS.map(group => ({
    type: 'group',
    label: t(group.labelKey),
    key: group.id,
    children: TEST_CASES
      .filter(testCase => testCase.group === group.id)
      .map(testCase => ({
        label: t(testCase.labelKey),
        value: testCase.id,
      })),
  }))
}
